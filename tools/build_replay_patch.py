"""Assemble tools/replay_patch.asm and write iop_replay_code.py (needs nasm).

The launcher ships the generated bytes, so nasm is only needed by developers.
"""
from pathlib import Path
import subprocess
import tempfile
import textwrap

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = ROOT / "tools" / "replay_patch.asm"
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "replay.bin"
        subprocess.run(["nasm", "-f", "bin", str(source), "-o", str(out)], check=True)
        data = out.read_bytes()
    if len(data) != 0x2000:
        raise SystemExit(f"unexpected section image size {len(data):#x}")
    code = data[:0x1000].rstrip(b"\0")
    ctrl = data[0x1000:].rstrip(b"\0")
    lines = textwrap.wrap(code.hex(), 96)
    body = "\n".join(f'    "{line}"' for line in lines)
    (ROOT / "iop_replay_code.py").write_text(
        '"""Generated by tools/build_replay_patch.py from tools/replay_patch.asm. Do not edit."""\n'
        f"CODE = bytes.fromhex(\n{body}\n)\n"
        f'CTRL_INIT = bytes.fromhex("{ctrl.hex()}")\n',
        encoding="utf-8",
    )
    print(f"code {len(code):#x} bytes")


if __name__ == "__main__":
    main()
